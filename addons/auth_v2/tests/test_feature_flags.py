"""Cross-language FNV-1a 32-bit parity test for the auth_v2 addon.

This test is the canonical Rule RF4 verification gate. It loads a
deterministic 100-vector JSON fixture generated by the TypeScript
canonical implementation at::

    packages/admin-ui/src/flags/__tests__/fixtures/fnv-vectors.json

and asserts that the Python ``fnv1a32(flag_name, subject)`` function in
``odoo.addons.auth_v2.models.fnv_hash`` produces byte-identical 32-bit
unsigned integer output for every vector.

The fixture is the cross-language ground truth: it is generated by the
TypeScript implementation in ``packages/admin-ui/src/flags/__tests__/
fnv-hash.spec.ts`` and loaded by both languages' test suites to assert
deterministic byte-equality.

Per Rule RF4, byte-equal output for ALL 100 vectors is required; there
are no tolerances, no skipped tests, no conditional skips by platform.

This test is purely computational -- it does NOT exercise the V2 sidecar
code paths, the flags API, the HTTP client, or any environment-variable
reads. The HTTP integration in ``auth_v2.py`` and ``feature_flags.py``
is out of scope for THIS test (covered by separate integration tests
in another agent's scope).

Five test methods are exposed:

    1. ``test_fixture_field_shape_and_ranges`` -- defensive pre-check that
       every fixture vector has the expected fields, types, and ranges so
       a corrupt fixture surfaces a clear diagnostic before the parity
       tests run with cryptic mismatch messages.

    2. ``test_fnv1a32_byte_parity`` -- THE Rule RF4 verification gate.
       For each of the 100 vectors, asserts ``fnv1a32(flag_name, subject)``
       returns the byte-identical 32-bit unsigned integer recorded in the
       fixture's ``expected_hash`` field.

    3. ``test_rollout_evaluation_parity`` -- asserts that the rollout
       decision ``(fnv1a32(flag_name, subject) % 100) < rollout_percentage``
       matches the fixture's ``expected_enabled`` boolean for every vector.
       Verifies the full 4-step evaluation produces byte-identical
       booleans across both languages.

    4. ``test_fnv1a32_default_subject_argument`` -- asserts that
       ``fnv1a32(name)`` and ``fnv1a32(name, '')`` produce identical
       output. This guards the most common Odoo call site
       (``feature_flags.is_enabled('AUTH_V2_ENABLED')``) against
       regression where the default argument is changed to ``None`` or
       similar non-string sentinel.

    5. ``test_fnv1a32_returns_uint32_range`` -- defensive test against
       sign-extension / overflow bugs. Asserts the function always
       returns an integer in ``[0, 0xFFFFFFFF]`` for both fixture inputs
       and ad-hoc edge cases (long inputs, control bytes, multi-byte
       UTF-8 characters).

See:
    - AAP Section 0.5.1.5 (Group 5 -- Odoo Addon)
    - AAP Section 0.7.2 RF4 (Flag determinism)
    - AAP Section 0.7.3.3 Gate 8 (Integration sign-off)
    - AAP Section 0.7.3.5 Gate 10 (Test execution)
    - blitzy-odoo/addons/auth_v2/models/fnv_hash.py (module under test)
    - packages/admin-ui/src/flags/fnv-hash.ts (TypeScript counterpart)
    - packages/admin-ui/src/flags/__tests__/fnv-hash.spec.ts (TS test/generator)
"""

import json
import os

from odoo.tests import TransactionCase, tagged

from odoo.addons.auth_v2.models.fnv_hash import fnv1a32

